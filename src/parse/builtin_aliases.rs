pub(crate) fn canonical_builtin_name(name: &str, kind: BuiltinAliasKind) -> &str {
    BUILTIN_ALIASES
        .iter()
        .find(|(short, _, alias_kind)| *short == name && *alias_kind == kind)
        .map_or(name, |(_, canonical, _)| *canonical)
}
