pub fn is_reserved_builtin_name(name: &str) -> bool {
    crate::parse::real_analysis_fact_arity(name).is_some()
        || name == "has_seq_limsup"
        || name == "has_seq_liminf"
        || name == "has_seq_limit"
        || name == "has_limit_at"
        || name == "has_limit_left"
        || name == "has_limit_right"
        || name == "has_limit_pos_inf"
        || name == "has_limit_neg_inf"
        || BuiltinTheoremId::from_name(name).is_some()
        || builtin_certificate_arity(name).is_some()
}

// Certificates owned by explicit introduction/projection theorem contracts.
// Recognizing their signature never proves their truth.
pub fn builtin_certificate_arity(name: &str) -> Option<usize> {
    match name {
        "is_antiderivative_on" => Some(3),
        "is_darboux_enclosure" => Some(7),
        "is_real_least_upper_bound" | "is_real_greatest_lower_bound" => Some(2),
        _ => None,
    }
}

