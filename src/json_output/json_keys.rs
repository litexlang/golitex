//! Localized JSON field names for Normal / Compact output.
//!
//! Code always authors English keys; `localize_key` remaps them when
//! a non-English output language is selected. Type / phase *values* are localized by explain
//! / helper match arms (not here).

use crate::launch_command::OutputLanguage;

pub fn localize_key(english_key: &str, lang: OutputLanguage) -> String {
    match lang {
        OutputLanguage::English => english_key.to_string(),
        OutputLanguage::Chinese => chinese_key(english_key).to_string(),
        OutputLanguage::ChineseTraditional => chinesetraditional_key(english_key).to_string(),
        OutputLanguage::French => french_key(english_key).to_string(),
        OutputLanguage::Russian => russian_key(english_key).to_string(),
        OutputLanguage::Spanish => spanish_key(english_key).to_string(),
        OutputLanguage::Arabic => arabic_key(english_key).to_string(),
        OutputLanguage::Japanese => japanese_key(english_key).to_string(),
        OutputLanguage::Korean => korean_key(english_key).to_string(),
        OutputLanguage::Vietnamese => vietnamese_key(english_key).to_string(),

    }
}

